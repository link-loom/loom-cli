export const detectLocale = (env = process.env) => {
  const value = env.LC_ALL || env.LC_MESSAGES || env.LANG || Intl.DateTimeFormat().resolvedOptions().locale || 'en';
  return String(value).toLowerCase().startsWith('es') ? 'es' : 'en';
};

export const getStrings = (locale) => STRINGS[locale] || STRINGS.en;

/** Schema prompts can be a plain string or `{ en, es }`. */
export const localize = (value, locale) => (value && typeof value === 'object' ? value[locale] || value.en : value);
